export function detectLanguage(query) {
  if (query?.lang && COPY[query.lang]) return query.lang;
  // `window` (not `navigator`) is the right browser-only guard here — recent
  // Node versions ship a global `navigator` on the server too, which used to
  // make this branch fire during SSR and return a different language than
  // the client, breaking hydration.
  if (typeof window !== "undefined") {
    const browserLang = navigator.language?.slice(0, 2);
    if (COPY[browserLang]) return browserLang;
  }
  return "pt";
}

// For components that need the detected language outside the URL-driven flow
// (e.g. dashboard pages, before a restaurant record is loaded). Starts at the
// SSR-safe default and only switches to the real browser language after
// mount, so the first client render still matches the server-rendered HTML.
export function useDetectedLanguage() {
  const [lang, setLang] = useState("pt");
  useEffect(() => { setLang(detectLanguage()); }, []);
  return lang;
}
